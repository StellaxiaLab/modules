// 이 저장소의 Go 모듈을 Terra 체크아웃과 한 워크스페이스로 묶는다.
//
// **왜 따로 있나** — `build-modules.mjs` 와 `test-modules.mjs` 가 같은 배선을
// 필요로 한다. 두 벌로 들고 있으면 모듈이 의존을 하나 더 쓸 때 한쪽만 조용히
// 틀린다 — `terraPackages` 가 목록을 손으로 들지 않고 go.mod 에서 읽는 것과
// 같은 이유다.
//
// **왜 go.work 인가** — 모듈의 `src/go.mod` 는 SDK 를 `../../../../products/...`
// 처럼 Terra 안을 가리키는 상대경로로 `replace` 한다. 이 저장소에는 그 경로가
// 없다. 모듈의 go.mod 를 고치면 이주가 파일 수정을 동반하게 되고 되돌리기도
// 어렵다. 대신 **go.work 의 replace 가 모듈의 replace 를 덮는다** — 생성물은
// 임시 디렉터리에 두므로 저장소에 남지 않는다(분리 검토 Q-8 — 나란한 체크아웃).

import { mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { existsSync, readdirSync } from 'node:fs';
import { spawn } from 'node:child_process';
import { tmpdir } from 'node:os';
import { dirname, isAbsolute, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const TIERS = ['common', 'leaf', 'tree'];

/**
 * `--terra` / `TERRA_CHECKOUT` 를 절대경로로 풀고 실제 Terra 인지 확인한다.
 * 확인을 생략하면 빈 디렉터리를 넘겼을 때 replace 가 없는 워크스페이스가 만들어져
 * "SDK 를 못 찾는다"는 엉뚱한 오류로 나타난다.
 */
export function resolveTerraRoot(terra) {
  if (!terra) {
    throw new Error(
      'Terra 체크아웃이 필요하다 — --terra <path> 또는 TERRA_CHECKOUT 환경변수.\n' +
        '모듈의 src/go.mod 가 그 안의 SDK 를 replace 로 가리키고, 그 SDK 는 공개 레지스트리에 없다.'
    );
  }
  const terraRoot = isAbsolute(terra) ? terra : resolve(repoRoot, terra);
  if (!existsSync(join(terraRoot, 'go.work'))) {
    throw new Error(`Terra 체크아웃이 아니다 (go.work 가 없다): ${terraRoot}`);
  }
  return terraRoot;
}

/** src/go.mod 를 가진 모듈만 — Scene·extension 은 빌드하거나 시험할 Go 가 없다. */
export function goModules() {
  const found = [];
  for (const tier of TIERS) {
    const tierDir = join(repoRoot, tier);
    if (!existsSync(tierDir)) continue;
    for (const entry of readdirSync(tierDir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      const dir = join(tierDir, entry.name);
      if (!existsSync(join(dir, 'src', 'go.mod'))) continue;
      if (!existsSync(join(dir, 'module.json'))) continue;
      found.push({ tier, id: entry.name, dir });
    }
  }
  return found;
}

/**
 * 이 모듈이 replace 로 끌어쓰는 Terra 패키지들. go.mod 를 읽어 모은다 —
 * 목록을 손으로 들고 있으면 모듈이 의존을 하나 더 쓸 때 조용히 틀린다.
 */
async function terraPackages(goModPath) {
  const text = await readFile(goModPath, 'utf8');
  const matched = text.matchAll(
    /(github\.com\/[\w.-]+\/[\w.-]+\/products\/common\/packages\/[a-z-]+)/g
  );
  return new Set([...matched].map((match) => match[1]));
}

/**
 * 모듈들과 Terra 패키지를 한 워크스페이스로 묶는다. `use` 와 `replace` 를 모두
 * 절대경로로 적는 이유는 이 파일이 저장소 밖(임시 디렉터리)에 살기 때문이다.
 *
 * @param generator 생성 주석에 적을 도구 이름 — 임시 파일이 남아 발견될 때
 *   누가 만들었는지가 보여야 한다.
 */
export async function writeWorkspace(modules, terraRoot, generator) {
  const goVersion = (await readFile(join(terraRoot, 'go.work'), 'utf8'))
    .split('\n')
    .find((line) => line.startsWith('go '))
    ?.slice(3)
    .trim();
  if (!goVersion) throw new Error(`Terra 의 go.work 에서 go 버전을 읽지 못했다: ${terraRoot}`);

  const replacements = new Set();
  for (const module of modules) {
    for (const pkg of await terraPackages(join(module.dir, 'src', 'go.mod'))) {
      replacements.add(pkg);
    }
  }

  const lines = [
    `// GENERATED by tools/${generator} — 임시 파일이다. 커밋하지 않는다.`,
    `go ${goVersion}`,
    ''
  ];
  for (const module of modules) lines.push(`use ${join(module.dir, 'src')}`);
  lines.push('');
  for (const pkg of [...replacements].sort()) {
    // github.com/<owner>/<repo>/products/... → <terra>/products/...
    const relative = pkg.slice(pkg.indexOf('/products/') + 1);
    lines.push(`replace ${pkg} => ${join(terraRoot, relative)}`);
  }
  lines.push('');

  const directory = await mkdtemp(join(tmpdir(), 'terra-modules-work-'));
  const path = join(directory, 'go.work');
  await writeFile(path, lines.join('\n'), 'utf8');
  return { path, replacements: replacements.size };
}

/** stdio 를 그대로 흘리고 종료 코드만 돌려준다 — CI 로그가 잡의 로그다. */
export function run(command, args, options) {
  return new Promise((done) => {
    const child = spawn(command, args, { stdio: 'inherit', ...options });
    child.on('close', (code) => done(code ?? 1));
  });
}
