#!/usr/bin/env node
// Master 위임 입구 대응표 — Terra 계약에서 src/api/master-delegated.js 를 만든다.
//
// leaf 노드의 Gateway 카탈로그에는 terra.master.* 가 없다. 그래서 leaf 화면은 Master op 를
// operation id 로 부르지 못하고 경로(/api/upstream/…)로 불러야 한다. 이 표가 op id → 경로다.
// 담는 것은 계약이 위임 입구(security.authentication 의 'delegated-session', Terra ADR-GW-003)로
// 연 op 뿐이다 — 앱 토큰으로 닿는 것만 경로로 부른다. 나머지는 부르지 않고 이유를 낸다.
//
//   node tools/gen-master-delegated.mjs --terra ../Terra           표를 다시 쓴다
//   node tools/gen-master-delegated.mjs --terra ../Terra --check   다르면 실패한다(CI)
// --terra 대신 TERRA_CHECKOUT 환경변수도 받는다.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outputPath = join(here, '..', 'src', 'api', 'master-delegated.js');
const CONTRACT = 'products/tree/master/contracts/api/terra-api.json';
const SCHEME = 'delegated-session';

/** 계약 → { op id: [method, path] } (id 순) */
export function buildTable(contract) {
  const table = {};
  for (const id of Object.keys(contract.operations).sort()) {
    const op = contract.operations[id];
    if (!(op.security?.authentication ?? []).includes(SCHEME)) continue;
    const b = (op.bindings ?? []).find((x) => x.method && x.path);
    if (!b) throw new Error(`${id}: 위임으로 열렸는데 HTTP 바인딩이 없다`);
    table[id] = [b.method.toUpperCase(), b.path];
  }
  return table;
}

export function render(table, version) {
  const rows = Object.entries(table).map(([id, [m, p]]) => `  '${id}': ['${m}', '${p}'],`);
  return [
    '// GENERATED by tools/gen-master-delegated.mjs — 손으로 고치지 않는다.',
    `// 원본: Terra ${CONTRACT} (terra.master.api ${version}) — security.authentication 에 '${SCHEME}' 이 있는 op`,
    '// leaf 화면이 이 op 들을 /api/upstream/… 경로로 부른다(client.js invokeUpstream · Terra ADR-GW-003).',
    '',
    '/** @type {Record<string, [string, string]>} op id → [method, Master 경로] */',
    'export const MASTER_DELEGATED = {',
    ...rows,
    '};',
    ''
  ].join('\n');
}

function main(argv) {
  const at = argv.indexOf('--terra');
  const terra = at >= 0 ? argv[at + 1] : process.env.TERRA_CHECKOUT;
  if (!terra) {
    console.error('Terra 체크아웃이 필요하다 — --terra <path> 또는 TERRA_CHECKOUT');
    process.exit(2);
  }
  const contract = JSON.parse(readFileSync(resolve(terra, CONTRACT), 'utf8'));
  const text = render(buildTable(contract), contract.contractVersion ?? contract.version ?? '?');
  if (argv.includes('--check')) {
    let now = '';
    try { now = readFileSync(outputPath, 'utf8'); } catch { /* 없다 */ }
    if (now !== text) {
      console.error('::error::src/api/master-delegated.js 가 Terra 계약과 다르다 — node tools/gen-master-delegated.mjs --terra <Terra> 로 다시 만든다');
      process.exit(1);
    }
    console.log('master-delegated.js: Terra 계약과 같다');
    return;
  }
  writeFileSync(outputPath, text);
  console.log(`master-delegated.js: ${Object.keys(buildTable(contract)).length} op`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
