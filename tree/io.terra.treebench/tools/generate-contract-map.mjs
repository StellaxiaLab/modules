// Regenerates ui/contract-map.js from the Master API contract.
//
// The Gateway catalog carries an operation's id, category, permissions and
// HTTP binding, but not two things Treebench needs: which authentication
// channel the operation answers on (a session app cannot call the device or
// service surfaces at all), and the field names inside its input areas. Both
// live in the contract, so they are baked here rather than guessed at runtime.
//
// Run from the repository root:
//   node module/tree/io.terra.treebench/tools/generate-contract-map.mjs
//
// src/contract_map_test.go fails if the checked-in file drifts from the
// contract, so regenerating is part of changing the Master API — not optional.
// It reimplements the projection below in Go rather than shelling out here, so
// it catches a stale file with no JS toolchain present.
//
// Deliberately not a CI step. If CI regenerated this file, a channel move would
// land without appearing in the diff a person reads — and that diff is the whole
// point of checking a generated file in. Failing loudly at the moment of the
// change is the behaviour we want; rewriting it quietly is not.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const moduleDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = join(moduleDir, '..', '..', '..');
const contractPath = join(repoRoot, 'products', 'tree', 'master', 'contracts', 'api', 'terra-api.json');
const outputPath = join(moduleDir, 'ui', 'contract-map.js');

const CHANNEL = {
  'terra-session': 's',
  'device-token': 'd',
  'service-credential': 'v',
  public: 'p',
};

export function buildMap(contract) {
  const map = {};
  for (const [id, operation] of Object.entries(contract.operations)) {
    const authentication = (operation.security?.authentication ?? ['terra-session'])[0];
    const entry = { c: CHANNEL[authentication] ?? 's' };
    const areas = operation.input?.schema?.properties ?? {};
    for (const [area, key] of [['body', 'b'], ['query', 'q']]) {
      const properties = areas[area]?.properties;
      if (!properties) continue;
      entry[key] = Object.keys(properties);
      const required = areas[area].required ?? [];
      if (required.length > 0) entry[`${key}r`] = required;
    }
    map[id.replace('terra.master.', '')] = entry;
  }
  return map;
}

export function render(map) {
  return [
    '// GENERATED by tools/generate-contract-map.mjs — do not edit.',
    '// Source: products/tree/master/contracts/api/terra-api.json (terra.master.api 1.0.0)',
    '// Drift is caught by src/contract_map_test.go.',
    '// c=channel s|d|v|p  b=body fields  br=required body  q=query fields  qr=required query',
    `window.TREEBENCH_CONTRACT_MAP=${JSON.stringify(map)};`,
    '',
  ].join('\n');
}

const contract = JSON.parse(readFileSync(contractPath, 'utf8'));
const map = buildMap(contract);
writeFileSync(outputPath, render(map));
console.log(`contract-map.js: ${Object.keys(map).length} operations`);
